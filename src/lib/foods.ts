/** Fluent 3D emoji görseli (lobehub paketi, jsdelivr üzerinden). */
export function emojiUrl(emoji: string): string {
  const hex = Array.from(emoji)
    .map((c) => c.codePointAt(0)!.toString(16))
    .join("-");
  return `https://cdn.jsdelivr.net/npm/@lobehub/fluent-emoji-3d@1.1.0/assets/${hex}.webp`;
}
